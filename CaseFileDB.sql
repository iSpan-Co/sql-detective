/* ---------- Suppliers ---------- */
CREATE TABLE Suppliers (
    SupplierID   INT            NOT NULL PRIMARY KEY,
    CompanyName  NVARCHAR(40)   NOT NULL,
    City         NVARCHAR(10)   NULL,
    Phone        VARCHAR(20)    NULL
);
GO

/* ---------- Products ---------- */
CREATE TABLE Products (
    ProductID    INT            NOT NULL PRIMARY KEY,
    ProductName  NVARCHAR(40)   NOT NULL,
    Category     NVARCHAR(10)   NOT NULL,
    UnitPrice    DECIMAL(10,2)  NOT NULL,
    Stock        INT            NOT NULL,
    SupplierID   INT            NOT NULL,
    CONSTRAINT FK_Products_Suppliers FOREIGN KEY (SupplierID) REFERENCES Suppliers(SupplierID)
);
GO

/* ---------- Employees ---------- */
CREATE TABLE Employees (
    EmployeeID   INT            NOT NULL PRIMARY KEY,
    Name         NVARCHAR(10)   NOT NULL,
    Dept         NVARCHAR(10)   NOT NULL,
    Title        NVARCHAR(20)   NULL,
    HireDate     DATE           NULL,
    ManagerID    INT            NULL,
    CONSTRAINT FK_Employees_Manager FOREIGN KEY (ManagerID) REFERENCES Employees(EmployeeID)
);
GO

/* ---------- Customers ---------- */
CREATE TABLE Customers (
    CustomerID   INT            NOT NULL PRIMARY KEY,
    Name         NVARCHAR(10)   NOT NULL,
    Email        VARCHAR(60)    NULL,
    Phone        VARCHAR(20)    NULL,
    City         NVARCHAR(10)   NULL,
    RegisterDate DATE           NOT NULL
);
GO

/* ---------- Coupons ---------- */
CREATE TABLE Coupons (
    CouponCode   VARCHAR(20)    NOT NULL PRIMARY KEY,
    DiscountRate DECIMAL(3,2)   NOT NULL,
    IssuedBy     INT            NOT NULL,
    ExpireDate   DATE           NULL,
    CONSTRAINT FK_Coupons_Employees FOREIGN KEY (IssuedBy) REFERENCES Employees(EmployeeID)
);
GO

/* ---------- Orders ---------- */
CREATE TABLE Orders (
    OrderID      INT            NOT NULL PRIMARY KEY,
    CustomerID   INT            NOT NULL,
    OrderDate    DATETIME       NOT NULL,
    Status       NVARCHAR(10)   NOT NULL,
    CouponCode   VARCHAR(20)    NULL,
    PaidAmount   DECIMAL(10,2)  NOT NULL,
    CONSTRAINT FK_Orders_Customers FOREIGN KEY (CustomerID) REFERENCES Customers(CustomerID),
    CONSTRAINT FK_Orders_Coupons   FOREIGN KEY (CouponCode) REFERENCES Coupons(CouponCode)
);
GO

/* ---------- OrderItems ---------- */
CREATE TABLE OrderItems (
    OrderID      INT            NOT NULL,
    ProductID    INT            NOT NULL,
    Qty          INT            NOT NULL,
    UnitPrice    DECIMAL(10,2)  NOT NULL,
    CONSTRAINT PK_OrderItems PRIMARY KEY (OrderID, ProductID),
    CONSTRAINT FK_OrderItems_Orders   FOREIGN KEY (OrderID)   REFERENCES Orders(OrderID),
    CONSTRAINT FK_OrderItems_Products FOREIGN KEY (ProductID) REFERENCES Products(ProductID)
);
GO

/* ---------- Refunds ---------- */
CREATE TABLE Refunds (
    RefundID     INT            NOT NULL PRIMARY KEY,
    OrderID      INT            NOT NULL,
    Amount       DECIMAL(10,2)  NOT NULL,
    RequestDate  DATETIME       NOT NULL,
    ApprovedBy   INT            NULL,
    BankAccount  VARCHAR(20)    NOT NULL,
    Reason       NVARCHAR(30)   NULL,
    CONSTRAINT FK_Refunds_Orders    FOREIGN KEY (OrderID)    REFERENCES Orders(OrderID),
    CONSTRAINT FK_Refunds_Employees FOREIGN KEY (ApprovedBy) REFERENCES Employees(EmployeeID)
);
GO

/* ---------- LoginLogs ---------- */
CREATE TABLE LoginLogs (
    LogID        INT            NOT NULL PRIMARY KEY,
    AccountType  NVARCHAR(4)    NOT NULL,   -- N'員工' 或 N'客戶'
    AccountID    INT            NOT NULL,   -- 員工時對應 EmployeeID，客戶時對應 CustomerID
    LoginTime    DATETIME       NOT NULL,
    IP           VARCHAR(20)    NOT NULL
);
GO

